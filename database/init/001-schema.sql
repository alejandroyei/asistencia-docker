CREATE TABLE IF NOT EXISTS roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS programs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR NOT NULL
);

CREATE TABLE IF NOT EXISTS subjects (
    id_subjects INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_subjects VARCHAR NOT NULL,
    status_subjects INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(150) NOT NULL,
    last_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255),
    microsoft_id VARCHAR(255),
    auth_provider VARCHAR(20) NOT NULL DEFAULT 'local',
    job_title VARCHAR(150),
    department VARCHAR(150),
    office_location VARCHAR(150),
    mobile_phone VARCHAR(50),
    business_phones VARCHAR,
    permissions JSONB,
    role_id INTEGER NOT NULL REFERENCES roles(id),
    program_id INTEGER NOT NULL REFERENCES programs(id),
    status_id INTEGER NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS programs_subjects (
    id_programs_subjects INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_programs INTEGER NOT NULL REFERENCES programs(id),
    id_subjects INTEGER NOT NULL REFERENCES subjects(id_subjects),
    status_programs_subject INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS promotions (
    id_promotion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_promotion VARCHAR(150) NOT NULL,
    id_programs INTEGER NOT NULL REFERENCES programs(id),
    status_promotions INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS groups (
    id_group INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    access_code_group VARCHAR(15) NOT NULL UNIQUE,
    id_subjects INTEGER NOT NULL REFERENCES subjects(id_subjects),
    id_promotion INTEGER NOT NULL REFERENCES promotions(id_promotion),
    id_programs INTEGER NOT NULL REFERENCES programs(id),
    status_group INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
    id_session INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_session DATE NOT NULL,
    day_session INTEGER NOT NULL,
    id_group INTEGER NOT NULL REFERENCES groups(id_group),
    status_session INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS registrations (
    id_registrations INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_users INTEGER NOT NULL REFERENCES users(id),
    id_groups INTEGER NOT NULL REFERENCES groups(id_group),
    status_registrations INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS attendances (
    id_attendances INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_attendances DATE NOT NULL,
    id_user INTEGER NOT NULL REFERENCES users(id),
    id_session INTEGER NOT NULL REFERENCES sessions(id_session),
    status_attendances INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_users_role_id ON users(role_id);
CREATE INDEX IF NOT EXISTS idx_users_program_id ON users(program_id);
CREATE INDEX IF NOT EXISTS idx_promotions_program_id ON promotions(id_programs);
CREATE INDEX IF NOT EXISTS idx_groups_subject_id ON groups(id_subjects);
CREATE INDEX IF NOT EXISTS idx_groups_promotion_id ON groups(id_promotion);
CREATE INDEX IF NOT EXISTS idx_groups_program_id ON groups(id_programs);
CREATE INDEX IF NOT EXISTS idx_sessions_group_id ON sessions(id_group);
CREATE INDEX IF NOT EXISTS idx_registrations_user_id ON registrations(id_users);
CREATE INDEX IF NOT EXISTS idx_registrations_group_id ON registrations(id_groups);
CREATE INDEX IF NOT EXISTS idx_attendances_user_id ON attendances(id_user);
CREATE INDEX IF NOT EXISTS idx_attendances_session_id ON attendances(id_session);

